#!/usr/bin/env node
// Builds the WordPress theme from the same sources as the static site.
//   node tools/build-wp.mjs
// wordpress/theme/ (hand-written PHP + wp.css)  +  src/pages/*.html  +  assets/
//   → dist/grainzmedia/      the installable theme
//   → dist/grainzmedia.zip   upload this in WordPress: Appearance → Themes → Add New → Upload Theme
import { readFileSync, writeFileSync, readdirSync, rmSync, mkdirSync, cpSync, existsSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { expandPictures } from './picture.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'dist/grainzmedia');
const manifest = JSON.parse(readFileSync(join(root, 'assets/img/photos/manifest.json'), 'utf8'));

rmSync(out, { recursive: true, force: true });
mkdirSync(join(out, 'pages'), { recursive: true });
const skip = src => !src.endsWith('.DS_Store');
cpSync(join(root, 'assets'), join(out, 'assets'), { recursive: true, filter: skip });
cpSync(join(root, 'wordpress/theme'), out, { recursive: true, filter: skip });
cpSync(join(root, 'assets/img/og-image.jpg'), join(out, 'screenshot.jpg'));

const php = s => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

// Static-site markup → theme template: page links and asset URLs become WordPress calls.
function toTemplate(html, file) {
  html = html.replace(/href="([a-z0-9-]+)\.html([?#][^"]*)?"/g, (_, slug, suffix) =>
    `href="<?php echo esc_url( gm_url( ${php(slug)}${suffix ? `, ${php(suffix)}` : ''} ) ); ?>"`);
  html = html.replace(/(["\s,])assets\//g, '$1<?php echo gm_assets(); ?>/');
  const left = html.match(/"[^"<]*\.html[^"]*"/);
  if (left) throw new Error(`${file}: unconverted link ${left[0]}`);
  return html;
}

const data = {};
for (const file of readdirSync(join(root, 'src/pages')).filter(f => f.endsWith('.html')).sort()) {
  const raw = readFileSync(join(root, 'src/pages', file), 'utf8');
  const m = raw.match(/^<!--\s*(\{[\s\S]*?\})\s*-->\s*/);
  if (!m) throw new Error(`${file}: missing front-matter comment`);
  const meta = JSON.parse(m[1]);
  const slug = (meta.out || file).replace(/\.html$/, '');
  const body = toTemplate(expandPictures(raw.slice(m[0].length), manifest), file);
  writeFileSync(join(out, 'pages', `${slug}.php`),
    `<?php // Generated from src/pages/${file} by tools/build-wp.mjs — edit the source, not this file. ?>\n${body.trim()}\n`);
  data[slug] = {
    title: meta.title,
    description: meta.description,
    nav: meta.nav || '',
    bodyClass: meta.bodyClass || '',
    preload: meta.preload ? manifest[meta.preload].widths.map(w => `assets/img/photos/${meta.preload}-${w}.webp ${w}w`).join(', ') : '',
  };
  console.log('built', `pages/${slug}.php`);
}

writeFileSync(join(out, 'inc/pages-data.php'),
  `<?php // Generated by tools/build-wp.mjs from the front matter in src/pages.\nreturn array(\n` +
  Object.entries(data).map(([slug, d]) =>
    `\t${php(slug)} => array( ${Object.entries(d).map(([k, v]) => `${php(k)} => ${php(v)}`).join(', ')} ),`).join('\n') +
  `\n);\n`);

const zip = join(root, 'dist/grainzmedia.zip');
if (existsSync(zip)) rmSync(zip);
execFileSync('zip', ['-rqX', 'grainzmedia.zip', 'grainzmedia'], { cwd: join(root, 'dist') });
console.log('built dist/grainzmedia/ and dist/grainzmedia.zip');
